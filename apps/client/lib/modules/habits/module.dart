/// Habits — an encouraging, one-tap habit tracker. Small progress made
/// visible, without guilt: missed intervals are forgiven explicitly, never
/// silently counted, and every number is a civil-date calculation the
/// README spells out.
class HabitsModule extends NexStoredModule {
  const HabitsModule();

  @override
  String get id => 'habits';

  @override
  IconData get icon => Icons.event_repeat_outlined;

  @override
  NexHue get hue => NexHue.teal;

  @override
  NexModuleStrings get strings => habitsStrings;

  @override
  Future<void> keepUp(NexModuleStore store, AppLocalizations l10n) =>
      habitsKeepUp(store, l10n);

  @override
  Future<String?> briefLine(NexModuleStore store, AppLocalizations l10n) async {
    final habits = (await store.list('habit')).map(Habit.fromRecord);
    final checks = (await store.list(
      'check',
    )).map(HabitCheck.fromRecord).toList();
    final firstDay = readFirstDay(await store.get('settings', 'week'));
    final now = DateTime.now();
    var remaining = 0;
    for (final habit in habits.where((h) => !h.archived)) {
      final s = HabitMath.fromChecks(
        habit,
        checks.where((c) => c.habitId == habit.id),
        now,
        firstDay: firstDay,
      );
      if (s.dueToday &&
          !s.todayDone &&
          !(habit.weekly && s.weekCount >= habit.target)) {
        remaining++;
      }
    }
    return remaining == 0
        ? null
        : strings.text(l10n, remaining == 1 ? 'briefOneLeft' : 'briefLeft', {
            'n': remaining,
          });
  }

  @override
  Widget screen(NexModuleStore store) => HabitsScreen(store: store);
}

